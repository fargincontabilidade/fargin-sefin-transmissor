import { open, sleep } from './e2e-lib.mjs';
import { fixture } from './fixture.mjs';
const out = process.argv[2];
const { b, p, errors } = await open('http://localhost:8080/index.html', { w: 390, h: 844, mobile: true, storage: fixture({ x: 5.5, y: 13 }) });
await sleep(2500);
await p.screenshot({ path: `${out}/m-title.png` });
await p.tap('text=Continuar');
await sleep(2500);
// usar o direcional por toque: arrastar para a direita
const pad = await p.$('.pad-base'); const bb = await pad.boundingBox();
const cx = bb.x + bb.width / 2, cy = bb.y + bb.height / 2;
const x0 = await p.evaluate(() => __mw.app.world.player.x);
const cdp = await p.context().newCDPSession(p);
await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: cx, y: cy }] });
await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: cx + 40, y: cy }] });
await sleep(900);
await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
const x1 = await p.evaluate(() => __mw.app.world.player.x);
console.log('moveu com toque:', Math.round(x1 - x0), 'px');
await p.screenshot({ path: `${out}/m-world.png` });
await p.evaluate(() => { const w = __mw.app.world; const pl = w.player; const t = w.wilds.sort((a,b)=>Math.hypot(a.x-pl.x,a.y-pl.y)-Math.hypot(b.x-pl.x,b.y-pl.y))[0]; w.startWildBattle(t); });
await sleep(4500);
await p.screenshot({ path: `${out}/m-battle.png` });
await p.tap('text=Atacar'); await sleep(400);
await p.screenshot({ path: `${out}/m-moves.png` });
await p.tap('.move-grid .move-btn >> nth=1'); await sleep(2200);
await p.screenshot({ path: `${out}/m-attack.png` });
console.log(errors.filter(e=>!/GL Driver|swiftshader|GPU stall/.test(e)).join('\n'));
await b.close();
